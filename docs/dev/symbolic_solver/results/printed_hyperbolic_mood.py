def hyperbolic(Q, Qaux, p, time, time_end, mesh, tok):
    def f1(time_2, Q_2, Qaux_2, n_write, tok_2):
        return (time_2 < time_end)
    def f2(time_3, Q_3, Qaux_3, n_write_2, tok_3):
        lam = face_wavespeed(nsm.eigenvalues_cfl, Q_3, Qaux_3, p, mesh)
        x3 = face_inradius(mesh)
        dt = reduce_min(0.45*x3/lam)
        dt_2 = minimum(minimum(5.0, -time_3 + time_end), dt)
        time_4 = time_3 + dt_2
        Qb, Qauxb = boundary_states(nsm.boundary_conditions, Q_3, Qaux_3, p, time_3, mesh)
        QL, QR = reconstruct(Q_3, Qaux_3, Qb, Qauxb, p, 2, False, mesh)
        QR_2 = boundary_traces(nsm.boundary_conditions, Q_3, QL, QR, Qaux_3, p, time_3, mesh)
        AL, AR = face_aux(Qaux_3, mesh)
        F = faces(nsm.numerical_flux, QL, QR_2, AL, AR, p, mesh)
        Dp, Dm = faces(nsm.numerical_fluctuations, QL, QR_2, AL, AR, p, mesh)
        x16 = divergence(F, Dp, Dm, mesh)
        x17 = edge_source(nsm.numerical_cell_edge_source, Q_3, QL, QR_2, Qaux_3, p, mesh)
        x18 = cells(nsm.source, Q_3, Qaux_3, p, time_3, dt_2, mesh)
        x19 = dt_2*(x18 - x16 - x17)
        Q_4 = Q_3 + x19
        Qaux_stage = cells(nsm.update_aux_variables, Q_4, Qaux_3, p, time_4, dt_2, mesh)
        Qb_2, Qauxb_2 = boundary_states(nsm.boundary_conditions, Q_4, Qaux_stage, p, time_4, mesh)
        QL_2, QR_3 = reconstruct(Q_4, Qaux_stage, Qb_2, Qauxb_2, p, 2, False, mesh)
        QR_4 = boundary_traces(nsm.boundary_conditions, Q_4, QL_2, QR_3, Qaux_stage, p, time_4, mesh)
        AL_2, AR_2 = face_aux(Qaux_stage, mesh)
        F_2 = faces(nsm.numerical_flux, QL_2, QR_4, AL_2, AR_2, p, mesh)
        Dp_2, Dm_2 = faces(nsm.numerical_fluctuations, QL_2, QR_4, AL_2, AR_2, p, mesh)
        x32 = divergence(F_2, Dp_2, Dm_2, mesh)
        x33 = edge_source(nsm.numerical_cell_edge_source, Q_4, QL_2, QR_4, Qaux_stage, p, mesh)
        x34 = cells(nsm.source, Q_4, Qaux_stage, p, time_4, dt_2, mesh)
        x35 = (1/2)*Q_3
        Q_5 = x35 + (1/2)*(Q_3 + x19 + dt_2*(x34 - x32 - x33))
        bad = inadmissible(nsm.admissible, Q_5, Qaux_3, p)
        x36 = reduce_any(bad)
        def f37():
            QL_3, QR_5 = reconstruct(Q_3, Qaux_3, Qb, Qauxb, p, 2, bad, mesh)
            QR_6 = boundary_traces(nsm.boundary_conditions, Q_3, QL_3, QR_5, Qaux_3, p, time_3, mesh)
            F_3 = faces(nsm.numerical_flux, QL_3, QR_6, AL, AR, p, mesh)
            Dp_3, Dm_3 = faces(nsm.numerical_fluctuations, QL_3, QR_6, AL, AR, p, mesh)
            x44 = divergence(F_3, Dp_3, Dm_3, mesh)
            x45 = edge_source(nsm.numerical_cell_edge_source, Q_3, QL_3, QR_6, Qaux_3, p, mesh)
            x46 = dt_2*(x18 - x44 - x45)
            Q_6 = Q_3 + x46
            Qaux_stage_2 = cells(nsm.update_aux_variables, Q_6, Qaux_3, p, time_4, dt_2, mesh)
            Qb_3, Qauxb_3 = boundary_states(nsm.boundary_conditions, Q_6, Qaux_stage_2, p, time_4, mesh)
            QL_4, QR_7 = reconstruct(Q_6, Qaux_stage_2, Qb_3, Qauxb_3, p, 2, bad, mesh)
            QR_8 = boundary_traces(nsm.boundary_conditions, Q_6, QL_4, QR_7, Qaux_stage_2, p, time_4, mesh)
            AL_3, AR_3 = face_aux(Qaux_stage_2, mesh)
            F_4 = faces(nsm.numerical_flux, QL_4, QR_8, AL_3, AR_3, p, mesh)
            Dp_4, Dm_4 = faces(nsm.numerical_fluctuations, QL_4, QR_8, AL_3, AR_3, p, mesh)
            x59 = divergence(F_4, Dp_4, Dm_4, mesh)
            x60 = edge_source(nsm.numerical_cell_edge_source, Q_6, QL_4, QR_8, Qaux_stage_2, p, mesh)
            x61 = cells(nsm.source, Q_6, Qaux_stage_2, p, time_4, dt_2, mesh)
            Q_7 = x35 + (1/2)*(Q_3 + x46 + dt_2*(x61 - x59 - x60))
            still = inadmissible(nsm.admissible, Q_7, Qaux_3, p)
            x62 = reduce_any(still)
            def f63():
                QL_5, QR_9 = reconstruct(Q_3, Qaux_3, Qb, Qauxb, p, 2, True, mesh)
                QR_10 = boundary_traces(nsm.boundary_conditions, Q_3, QL_5, QR_9, Qaux_3, p, time_3, mesh)
                F_5 = faces(nsm.numerical_flux, QL_5, QR_10, AL, AR, p, mesh)
                Dp_5, Dm_5 = faces(nsm.numerical_fluctuations, QL_5, QR_10, AL, AR, p, mesh)
                x70 = divergence(F_5, Dp_5, Dm_5, mesh)
                x71 = edge_source(nsm.numerical_cell_edge_source, Q_3, QL_5, QR_10, Qaux_3, p, mesh)
                x72 = dt_2*(x18 - x70 - x71)
                Q_8 = Q_3 + x72
                Qaux_stage_3 = cells(nsm.update_aux_variables, Q_8, Qaux_3, p, time_4, dt_2, mesh)
                Qb_4, Qauxb_4 = boundary_states(nsm.boundary_conditions, Q_8, Qaux_stage_3, p, time_4, mesh)
                QL_6, QR_11 = reconstruct(Q_8, Qaux_stage_3, Qb_4, Qauxb_4, p, 2, True, mesh)
                QR_12 = boundary_traces(nsm.boundary_conditions, Q_8, QL_6, QR_11, Qaux_stage_3, p, time_4, mesh)
                AL_4, AR_4 = face_aux(Qaux_stage_3, mesh)
                F_6 = faces(nsm.numerical_flux, QL_6, QR_12, AL_4, AR_4, p, mesh)
                Dp_6, Dm_6 = faces(nsm.numerical_fluctuations, QL_6, QR_12, AL_4, AR_4, p, mesh)
                x85 = divergence(F_6, Dp_6, Dm_6, mesh)
                x86 = edge_source(nsm.numerical_cell_edge_source, Q_8, QL_6, QR_12, Qaux_stage_3, p, mesh)
                x87 = cells(nsm.source, Q_8, Qaux_stage_3, p, time_4, dt_2, mesh)
                return (x35 + (1/2)*(Q_3 + x72 + dt_2*(x87 - x85 - x86)), tok_3, )
            def f88():
                return (Q_7, tok_3, )
            x90, _ = cond(x62, f63, f88)
            return (x90, tok_3, )
        def f91():
            return (Q_5, tok_3, )
        Q_9, _ = cond(x36, f37, f91)
        Qaux_4 = cells(nsm.update_aux_variables, Q_9, Qaux_3, p, time_4, dt_2, mesh)
        Qaux_5 = derivative_aux(Q_9, Qaux_4, mesh)
        return (time_4, Q_9, Qaux_5, n_write_2, tok_3, )
    time_5, Q_10, Qaux_6, _, x98 = while_loop(f1, f2, (time, Q, Qaux, 1, tok, ))
    return (time_5, Q_10, Qaux_6, x98, )
