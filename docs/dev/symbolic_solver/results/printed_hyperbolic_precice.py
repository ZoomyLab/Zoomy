def hyperbolic_precice(Q, Qaux, p, time, mesh, tok):
    def f1(time_2, Q_2, Qaux_2, going, tok_2):
        return going
    def f2(time_3, Q_3, Qaux_3, going_2, tok_3):
        x4, x5 = couple_max_dt(tok_3)
        lam = face_wavespeed(nsm.eigenvalues_cfl, Q_3, Qaux_3, p, mesh)
        x6 = face_inradius(mesh)
        dt = reduce_min(1.8*x6/lam)
        dt_2 = minimum(minimum(5.0, x5), dt)
        time_4 = time_3 + dt_2
        Qb, Qauxb = boundary_states(nsm.boundary_conditions, Q_3, Qaux_3, p, time_3, mesh)
        QL, QR = reconstruct(Q_3, Qaux_3, Qb, Qauxb, p, 2, False, mesh)
        QR_2 = boundary_traces(nsm.boundary_conditions, Q_3, QL, QR, Qaux_3, p, time_3, mesh)
        AL, AR = face_aux(Qaux_3, mesh)
        F = faces(nsm.numerical_flux, QL, QR_2, AL, AR, p, mesh)
        Dp, Dm = faces(nsm.numerical_fluctuations, QL, QR_2, AL, AR, p, mesh)
        mask = coupled_faces(mesh)
        x20, peer = couple_read(x4, dt_2)
        Fc = interface_flux(nsm.numerical_flux, nsm.numerical_fluctuations, 0, Q_3, Qaux_3, peer, p, mesh)
        Dm_2 = select(mask, Fc - F, Dm)
        x22 = divergence(F, Dp, Dm_2, mesh)
        x23 = edge_source(nsm.numerical_cell_edge_source, Q_3, QL, QR_2, Qaux_3, p, mesh)
        x24 = cells(nsm.source, Q_3, Qaux_3, p, time_3, dt_2, mesh)
        x25 = dt_2*(x24 - x22 - x23)
        Q_4 = Q_3 + x25
        Qaux_stage = cells(nsm.update_aux_variables, Q_4, Qaux_3, p, time_4, dt_2, mesh)
        Qb_2, Qauxb_2 = boundary_states(nsm.boundary_conditions, Q_4, Qaux_stage, p, time_4, mesh)
        QL_2, QR_3 = reconstruct(Q_4, Qaux_stage, Qb_2, Qauxb_2, p, 2, False, mesh)
        QR_4 = boundary_traces(nsm.boundary_conditions, Q_4, QL_2, QR_3, Qaux_stage, p, time_4, mesh)
        AL_2, AR_2 = face_aux(Qaux_stage, mesh)
        F_2 = faces(nsm.numerical_flux, QL_2, QR_4, AL_2, AR_2, p, mesh)
        Dp_2, Dm_3 = faces(nsm.numerical_fluctuations, QL_2, QR_4, AL_2, AR_2, p, mesh)
        Dm_4 = select(mask, Fc - F_2, Dm_3)
        x38 = divergence(F_2, Dp_2, Dm_4, mesh)
        x39 = edge_source(nsm.numerical_cell_edge_source, Q_4, QL_2, QR_4, Qaux_stage, p, mesh)
        x40 = cells(nsm.source, Q_4, Qaux_stage, p, time_4, dt_2, mesh)
        Q_5 = (1/2)*Q_3 + (1/2)*(Q_3 + x25 + dt_2*(x40 - x38 - x39))
        Qaux_4 = cells(nsm.update_aux_variables, Q_5, Qaux_3, p, time_4, dt_2, mesh)
        Qaux_5 = derivative_aux(Q_5, Qaux_4, mesh)
        x41 = interface_states(Q_5, mesh)
        x43, = couple_write(x20, x41)
        x45, going_3 = couple_advance(x43, dt_2)
        return (time_4, Q_5, Qaux_5, going_3, x45, )
    x47 = interface_states(Q, mesh)
    x49, going_4 = couple_init(tok, x47)
    time_5, Q_6, Qaux_6, _, x55 = while_loop(f1, f2, (time, Q, Qaux, going_4, x49, ))
    return (time_5, Q_6, Qaux_6, x55, )
