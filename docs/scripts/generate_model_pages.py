"""The generated equations of the Model guide pages, written to docs/_generated/model_*.md.

    python docs/scripts/generate_model_pages.py

`guide/model.md` includes `model_swe.md`, `guide/models/sme.md` includes `model_sme.md` and
`guide/models/mlvam.md` includes `model_mlvam.md`.  Every equation comes from the code:

* SWE is written as operators (`flux`, `nonconservative_matrix`, `source`), so its file is
  `Model.summarize_model()`.
* SME and MLVAM are derived symbolically.  Their files are the rows of `model.derivation`,
  the derived equation set that `model.derivation.describe()` prints, rendered for MathJax:
  coordinate arguments are dropped (`h(t, x)` prints as `h`), the terms of a row are grouped
  by their derivative factor with each coefficient cancelled (an exact identity), rows that
  are identically `0 = 0` are left out, and a long row is broken over several lines.
"""
from __future__ import annotations

import sys
import time
from pathlib import Path

import sympy as sp
from sympy.core.function import AppliedUndef
from sympy.printing.latex import LatexPrinter

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "docs" / "_generated"
for _lib in ("zoomy_core", "zoomy_jax"):
    sys.path.insert(0, str(ROOT / "library" / _lib))

from zoomy_core import coords as C  # noqa: E402
from zoomy_core.model.models import (  # noqa: E402
    SWE, SME, MLVAM, Newtonian, NavierSlip, StressFree)

COORDS = {C.t, C.x, C.y, C.z, sp.Symbol("zeta", real=True)}
LINE_CHARS = 200
HEADER = "<!-- generated by docs/scripts/generate_model_pages.py, do not edit -->\n\n"


class _Printer(LatexPrinter):
    """LaTeX without the coordinate arguments of the fields (`q_1(0, t, x)` prints as `q_{1,0}`),
    derivatives as `\\partial_x`, and the `HydrostaticPressure` tag as its argument."""

    def _print_Function(self, expr, exp=None):
        if type(expr).__name__ == "HydrostaticPressure":
            return self._print(expr.args[0])
        if not isinstance(expr, AppliedUndef):
            return super()._print_Function(expr, exp)
        idx = [a for a in expr.args if a not in COORDS]
        if any(not a.is_Integer for a in idx):
            return super()._print_Function(expr, exp)
        name = name_tex(expr.func.__name__, [str(a) for a in idx])
        return f"{name}^{{{exp}}}" if exp is not None else name

    def _print_Derivative(self, expr):
        ops = "".join(rf"\partial_{{{self._print(v)}}}" if n == 1
                      else rf"\partial_{{{self._print(v)}}}^{{{n}}}"
                      for v, n in expr.variable_count)
        e = expr.expr
        if isinstance(e, (AppliedUndef, sp.Symbol)):
            return f"{ops} {self._print(e)}"
        # the shortest of three exactly equal forms of a flux
        forms = [e, sp.factor(sp.cancel(sp.together(e))),
                 sp.Add(*[sp.factor(t) for t in sp.Add.make_args(sp.expand(e))])]
        inner = min((self._print(f) for f in forms), key=len)
        return rf"{ops} \left({inner}\right)"


def name_tex(name, extra=()):
    """`q_1_0` (or `q_1` with the extra index `0`) as `q_{1,0}`."""
    head, *sub = name.split("_")
    sub = [*sub, *extra]
    base = LatexPrinter()._deal_with_super_sub(head)
    return f"{base}_{{{','.join(sub)}}}" if sub else base


def tex(expr):
    """LaTeX of `expr` with the field arguments dropped."""
    return _Printer({"mul_symbol": None}).doprint(expr)


def _split(term):
    """`(coefficient, derivative part)` of one product term."""
    coef, ders = sp.S.One, sp.S.One
    for f in sp.Mul.make_args(term):
        if f.has(sp.Derivative):
            ders *= f
        else:
            coef *= f
    return coef, ders


def _order(ders):
    """Sort key: time derivatives, then conservative fluxes, then the other derivative terms."""
    if ders == 1:
        return (3, "")
    d = [a for a in sp.Mul.make_args(ders) if isinstance(a, sp.Derivative)]
    if any(C.t in a.variables for a in d):
        return (0, sp.srepr(ders))
    if len(d) == 1 and ders == d[0] and not isinstance(d[0].expr, AppliedUndef):
        return (1, sp.srepr(ders))
    return (2, sp.srepr(ders))


def _terms(expr):
    """`expr` over a common denominator, split into its cancelled monomial terms."""
    num, den = sp.fraction(sp.cancel(sp.together(expr)))
    return [sp.cancel(t / den) for t in sp.Add.make_args(sp.expand(num))]


def grouped_terms(expr):
    """`(coefficient, derivative part)` pairs of `expr`: one pair per derivative factor with the
    coefficient cancelled, and each derivative-free monomial on its own.  Their sum is `expr`."""
    groups = {}
    for term in sp.Add.make_args(sp.expand(expr)):
        coef, ders = _split(term)
        groups[ders] = groups.get(ders, sp.S.Zero) + coef
    out = []
    for ders in sorted(groups, key=_order):
        if ders == 1:
            out += [(t, ders) for t in _terms(groups[ders]) if t != 0]
            continue
        coef = sp.factor(sp.cancel(sp.together(groups[ders])))
        if coef != 0:
            out.append((coef, ders))
    rebuilt = sum((c * d for c, d in out), sp.S.Zero)
    num, _ = sp.fraction(sp.together(sp.expand(rebuilt - expr)))
    assert sp.expand(num) == 0, "regrouping changed the row"
    return out


def _piece(coef, ders):
    """`(sign, LaTeX)` of one term."""
    neg = coef.could_extract_minus_sign()
    c = -coef if neg else coef
    if ders == 1:
        body = tex(c)
    elif c == 1:
        body = tex(ders)
    elif isinstance(c, sp.Add):
        body = rf"\left({tex(c)}\right) {tex(ders)}"
    else:
        body = rf"{tex(c)} \, {tex(ders)}"
    return ("-" if neg else "+"), body


def row_latex(expr):
    """Display LaTeX of the row `expr = 0`, broken into lines of about `LINE_CHARS` characters."""
    pieces = [_piece(c, d) for c, d in grouped_terms(expr)]
    if not pieces:
        return None
    lines, line = [], ""
    for i, (sign, body) in enumerate(pieces):
        item = ("- " if sign == "-" else "") + body if i == 0 else f"{sign} {body}"
        if line and len(line) + len(item) > LINE_CHARS:
            lines.append(line)
            line = item
        else:
            line = f"{line} {item}".strip()
    lines.append(line)
    if len(lines) == 1:
        return lines[0] + " = 0"
    body = r" \\ &\quad ".join(lines)
    return r"\begin{aligned} &" + body + r" = 0 \end{aligned}"


def rows_md(rows):
    """Markdown of named rows, one display equation each.  Rows `0 = 0` are left out."""
    parts = []
    for name, expr in rows:
        ltx = row_latex(expr)
        if ltx is not None:
            parts.append(f"`{name}`\n\n$$\n{ltx}\n$$")
    return "\n\n".join(parts)


def parameters_md(values):
    """The default parameter values, by the names `parameters=` takes."""
    return ", ".join(f"`{k}` = {v}" for k, v in values.items())


def state_md(model):
    """The state vector of the lifted SystemModel."""
    from zoomy_core.systemmodel import SystemModel
    sm = SystemModel.from_model(model)
    return ", ".join(f"${name_tex(str(s))}$" for s in sm.state)


def closures():
    """The closure set of the SME and VAM tutorials and goldens."""
    return [Newtonian(), NavierSlip(), StressFree()]


def swe_page():
    """SWE: the operator form of `Model.summarize_model`."""
    m = SWE()
    s = m.summarize_model(tex=True)
    parts = [
        f"**State $Q$:** {', '.join(f'${name_tex(str(v))}$' for v in m.variables.values())}",
        f"**Parameters:** {parameters_md(s['parameters'])}",
        f"$$\n{s['pde_form']}\n$$",
        f"$$\nQ = {s['Q']}, \\quad F_x = {s['F']}, \\quad P_x = {s['P'] or 0}\n$$",
        f"$$\nB_x = {s['B']['x']}, \\quad S = {s['S']}\n$$",
    ]
    return "\n\n".join(parts)


def sme_page():
    """SME(level=1): the derived rows."""
    m = SME(level=1, dimension=2, closures=closures())
    der = m.derivation
    rows = [(n, e.expr) for n, e in der._equations.items()]
    parts = [
        "`SME(level=1, dimension=2, closures=[Newtonian(), NavierSlip(), StressFree()])`",
        f"**State $Q$:** {state_md(m)}",
        f"**Parameters:** {parameters_md(dict(der.parameter_values.items()))}",
        rows_md(rows),
    ]
    return "\n\n".join(parts)


def mlvam_page():
    """MLVAM(n_layers=2, level=1): the derived rows, grouped by layer."""
    m = MLVAM(n_layers=2, level=1, dimension=2, closures=closures())
    der = m.derivation
    eqs = {n: e.expr for n, e in der._equations.items()}
    parts = [
        "`MLVAM(n_layers=2, level=1, dimension=2, closures=[Newtonian(), NavierSlip(), StressFree()])`",
        f"**State $Q$:** {state_md(m)}",
        f"**Parameters:** {parameters_md(dict(der.parameter_values.items()))}",
        "**Bed and total depth**",
        rows_md([(n, eqs[n]) for n in ("bottom", "continuity")]),
    ]
    for ell in range(1, int(m.n_layers) + 1):
        mine = [(n, e) for n, e in eqs.items()
                if n.split("_")[-2:-1] == [str(ell)] and n not in ("bottom", "continuity")]
        parts += [f"**Layer {ell}**", rows_md(mine)]
    return "\n\n".join(parts)


PAGES = {"swe": swe_page, "sme": sme_page, "mlvam": mlvam_page}


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    t0 = time.time()
    for name, build in PAGES.items():
        t = time.time()
        (OUT / f"model_{name}.md").write_text(HEADER + build() + "\n", encoding="utf-8")
        print(f"model_{name}.md  {time.time() - t:.1f} s")
    print(f"generate_model_pages: {time.time() - t0:.1f} s")


if __name__ == "__main__":
    main()
