# ---------------------------------------------------------------------------
# LSQ gradient accuracy on polynomial test functions
# ---------------------------------------------------------------------------
@pytest.mark.skipif(not _HAVE_PETSC, reason="PETSc not available")
class TestLSQGradientAccuracy:
    """Verify LSQ gradient reconstruction on polynomial test functions."""

    def _load_mesh(self, case):
        msh_path = REF_DIR / f"test_{case}.msh"
        if not msh_path.exists():
            pytest.skip(f"MSH file not found: {msh_path}")
        return PetscMesh.from_gmsh(str(msh_path))

    @pytest.mark.parametrize("case", ["square_quad", "triangle", "channel_hole"])
    def test_linear_gradient_2d(self, case):
        """For u(x,y) = 2x + 3y, gradient should be [2, 3] everywhere."""
        from zoomy_core.mesh.lsq_reconstruction import compute_derivatives

        m = self._load_mesh(case)
        dim = m.dimension
        centers = m.cell_centers[:dim, :].T  # (n_cells, dim)
        u = 2 * centers[:, 0] + 3 * centers[:, 1]

        grad = compute_derivatives(u, m, derivatives_multi_index=[(1, 0), (0, 1)])
        n_inner = m.n_inner_cells

        np.testing.assert_allclose(grad[:n_inner, 0], 2.0, atol=1e-5)
        np.testing.assert_allclose(grad[:n_inner, 1], 3.0, atol=1e-5)

    def test_linear_gradient_3d(self):
        """For u(x,y,z) = x + 2y + 3z, gradient should be [1, 2, 3]."""
        from zoomy_core.mesh.lsq_reconstruction import compute_derivatives

        m = self._load_mesh("tetra3d")
        dim = m.dimension
        centers = m.cell_centers[:dim, :].T
        u = centers[:, 0] + 2 * centers[:, 1] + 3 * centers[:, 2]

        grad = compute_derivatives(
            u, m, derivatives_multi_index=[(1, 0, 0), (0, 1, 0), (0, 0, 1)]
        )
        n_inner = m.n_inner_cells

        np.testing.assert_allclose(grad[:n_inner, 0], 1.0, atol=1e-6)
        np.testing.assert_allclose(grad[:n_inner, 1], 2.0, atol=1e-6)
        np.testing.assert_allclose(grad[:n_inner, 2], 3.0, atol=1e-6)


