class TestLSQMeshGradient:
    @pytest.mark.parametrize("case", ["square_quad", "triangle", "channel_hole"])
    def test_linear_gradient_2d(self, case):
        m = LSQMesh.from_msh(str(REF_DIR / f"test_{case}.msh"))
        dim = m.dimension
        centers = m.cell_centers_computed()[:dim, :].T
        u = 2 * centers[:, 0] + 3 * centers[:, 1]
        grad = m.compute_derivatives(u, derivatives_multi_index=[(1, 0), (0, 1)])
        n = m.n_inner_cells
        np.testing.assert_allclose(grad[:n, 0], 2.0, atol=1e-5)
        np.testing.assert_allclose(grad[:n, 1], 3.0, atol=1e-5)

    def test_linear_gradient_3d(self):
        m = LSQMesh.from_msh(str(REF_DIR / "test_tetra3d.msh"))
        centers = m.cell_centers_computed()[:3, :].T
        u = centers[:, 0] + 2 * centers[:, 1] + 3 * centers[:, 2]
        grad = m.compute_derivatives(
            u, derivatives_multi_index=[(1, 0, 0), (0, 1, 0), (0, 0, 1)]
        )
        n = m.n_inner_cells
        np.testing.assert_allclose(grad[:n, 0], 1.0, atol=1e-5)
        np.testing.assert_allclose(grad[:n, 1], 2.0, atol=1e-5)
        np.testing.assert_allclose(grad[:n, 2], 3.0, atol=1e-5)

    def test_1d_gradient(self):
        m = LSQMesh.create_1d((0, 1), 20)
        centers = m.cell_centers_computed()[:1, :].T
        u = 5.0 * centers[:, 0]
        grad = m.compute_derivatives(u, derivatives_multi_index=[(1,)])
        n = m.n_inner_cells
        np.testing.assert_allclose(grad[:n, 0], 5.0, atol=1e-5)
