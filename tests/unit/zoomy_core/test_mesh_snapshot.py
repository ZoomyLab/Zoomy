"""Snapshot tests: compare new mesh implementations against PETSc reference data.

Reference .npz files were generated by loading .msh files through the current
PETSc-based Mesh.from_gmsh() and saving all 33 fields.  These tests verify
that the new pure-numpy mesh classes reproduce the same results.
"""

import os
from pathlib import Path

import numpy as np
import pytest

REF_DIR = Path(__file__).parent / "mesh_references"

MESH_CASES = ["square_quad", "triangle", "tetra3d", "channel_hole"]


def _load_ref(name):
    path = REF_DIR / f"ref_{name}.npz"
    if not path.exists():
        pytest.skip(f"Reference file not found: {path}")
    return dict(np.load(str(path), allow_pickle=True))


# ---------------------------------------------------------------------------
# Geometry field names that should match PETSc within tolerance
# ---------------------------------------------------------------------------
GEOMETRY_FIELDS = [
    "cell_centers",
    "cell_volumes",
    "cell_inradius",
    "face_normals",
    "face_volumes",
    "face_centers",
    "face_subvolumes",
]

TOPOLOGY_FIELDS = [
    "vertex_coordinates",
    "cell_vertices",
    "cell_faces",
    "face_cells",
    "cell_neighbors",
]

BOUNDARY_FIELDS = [
    "boundary_face_cells",
    "boundary_face_ghosts",
    "boundary_face_function_numbers",
    "boundary_face_physical_tags",
    "boundary_face_face_indices",
    "boundary_conditions_sorted_physical_tags",
]

SCALAR_FIELDS = [
    "dimension",
    "n_cells",
    "n_inner_cells",
    "n_faces",
    "n_vertices",
    "n_boundary_faces",
    "n_faces_per_cell",
]

LSQ_FIELDS = [
    "lsq_gradQ",
    "lsq_neighbors",
    "lsq_scale_factors",
]


# ---------------------------------------------------------------------------
# Reference data sanity checks (ensure the snapshots are loadable)
# ---------------------------------------------------------------------------
class TestReferenceDataLoads:
    @pytest.mark.parametrize("case", MESH_CASES)
    def test_ref_has_all_fields(self, case):
        ref = _load_ref(case)
        for field in SCALAR_FIELDS + TOPOLOGY_FIELDS + GEOMETRY_FIELDS + BOUNDARY_FIELDS + LSQ_FIELDS:
            assert field in ref, f"Missing field '{field}' in ref_{case}.npz"

    @pytest.mark.parametrize("case", MESH_CASES)
    def test_ref_scalars_sensible(self, case):
        ref = _load_ref(case)
        assert int(ref["dimension"]) in (1, 2, 3)
        assert int(ref["n_inner_cells"]) > 0
        assert int(ref["n_faces"]) > 0
        assert int(ref["n_vertices"]) > 0
        assert int(ref["n_cells"]) >= int(ref["n_inner_cells"])

    @pytest.mark.parametrize("case", MESH_CASES)
    def test_ref_volumes_positive(self, case):
        ref = _load_ref(case)
        n_inner = int(ref["n_inner_cells"])
        assert np.all(ref["cell_volumes"][:n_inner] > 0)
        assert np.all(ref["face_volumes"] > 0)

    @pytest.mark.parametrize("case", MESH_CASES)
    def test_ref_normals_unit(self, case):
        ref = _load_ref(case)
        dim = int(ref["dimension"])
        normals = ref["face_normals"][:dim, :]
        norms = np.linalg.norm(normals, axis=0)
        np.testing.assert_allclose(norms, 1.0, atol=1e-12)


