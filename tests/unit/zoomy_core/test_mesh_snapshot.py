class TestBaseMeshFromMsh:
    """BaseMesh.from_msh() topology should match PETSc reference."""

    @pytest.mark.parametrize("case", MESH_CASES)
    def test_counts_match(self, case):
        ref = _load_ref(case)
        msh_path = REF_DIR / f"test_{case}.msh"
        m = BaseMesh.from_msh(str(msh_path))
        assert m.n_inner_cells == int(ref["n_inner_cells"])
        assert m.n_faces == int(ref["n_faces"])
        assert m.n_vertices == int(ref["n_vertices"])
        assert m.n_cells == int(ref["n_cells"])
        assert m.n_boundary_faces == int(ref["n_boundary_faces"])

    @pytest.mark.parametrize("case", MESH_CASES)
    def test_h5_roundtrip(self, case, tmp_path):
        msh_path = REF_DIR / f"test_{case}.msh"
        m = BaseMesh.from_msh(str(msh_path))
        h5_path = str(tmp_path / f"{case}.h5")
        m.write_to_hdf5(h5_path)
        m2 = BaseMesh.from_hdf5(h5_path)
        assert m2.n_cells == m.n_cells
        assert m2.n_faces == m.n_faces
        np.testing.assert_array_equal(m2.cell_vertices, m.cell_vertices)
        np.testing.assert_array_equal(m2.face_cells, m.face_cells)


