"""Regenerate the JS kernel fixtures used by the zoomy_js solver tests.

Runs the *real* zoomy_core codegen (JsModel / JsNumerics + BC printer)
for a minimal 2D Shallow Water model with a Wall boundary, so the
solver tests exercise the actual generated kernels — not a
hand-written stand-in.

Run from the ``zoomy`` conda env::

    python library/zoomy_js/test/gen_fixtures.py

Writes ``test/fixtures/swe2d.generated.js`` (an ES module: every
generated ``function`` is re-exported at the bottom).
"""

import re
from pathlib import Path

from sympy import Matrix, sqrt

from zoomy_core.misc.misc import ZArray, Zstruct
from zoomy_core.model.basefunction import Function
from zoomy_core.model.basemodel import Model
from zoomy_core.model.boundary_conditions import BoundaryConditions, Wall
from zoomy_core.fvm.riemann_solvers import HLLC
from zoomy_core.transformation.to_js import JsModel, JsNumerics


def per_tag_bc_kernels(model, printer):
    """Codegen one kernel per boundary tag (``bc_<tag>``) — see the
    matching helper in apps/swe-game/generate.py."""
    m = model
    blocks = []
    for bc in m.boundary_conditions.boundary_conditions_list:
        defn = bc.compute_boundary_condition(
            m.time, m.position.get_list(), m.distance,
            m.variables.get_list(), m.aux_variables.get_list(),
            m._parameter_symbols.get_list(), m.normal.get_list(),
        )
        fn = Function(
            name=f"bc_{bc.tag}",
            args=Zstruct(
                time=m.time, position=m.position, distance=m.distance,
                variables=m.variables, aux_variables=m.aux_variables,
                parameters=m._parameter_symbols, normal=m.normal,
            ),
            definition=defn,
        )
        blocks.append(printer._generate_bc_kernel(fn))
    return "\n\n".join(blocks)


class MiniSWE(Model):
    """2D Shallow Water Equations, state [h, hu, hv], gravity ``g``."""

    def __init__(self, **kwargs):
        super().__init__(
            dimension=2,
            variables=["h", "hu", "hv"],
            parameters={"g": (9.81, "positive")},
            eigenvalue_mode="symbolic",
            **kwargs,
        )

    def flux(self):
        h = self.variables[0]
        hu = Matrix(self.variables[1:])
        u = hu / h
        g = self._parameter_symbols.g
        F = Matrix.zeros(self.n_variables, self.dimension)
        F[0, :] = hu.T
        F[1:, :] = h * u * u.T + 0.5 * g * h**2 * Matrix.eye(self.dimension)
        return ZArray(F)

    def eigenvalues(self):
        h = self.variables[0]
        hu = Matrix(self.variables[1:])
        n = Matrix(self.normal[:2])
        g = self._parameter_symbols.g
        un = (hu.T * n)[0] / h
        c = sqrt(g * h)
        return ZArray([un - c, un + c, un])


def main():
    model = MiniSWE(
        boundary_conditions=BoundaryConditions(
            [Wall(tag="wall", momentum_field_indices=[[1, 2]])]
        )
    )
    numerics = HLLC(model)

    blocks = [
        "// AUTO-GENERATED by library/zoomy_js/test/gen_fixtures.py — do not edit.",
        "// Real zoomy_core codegen output (MiniSWE + HLLC + Wall BC).",
        JsModel(model).generate(),
        JsNumerics(numerics).generate(),
        per_tag_bc_kernels(model, JsModel(model)),
    ]
    code = "\n\n".join(blocks)

    names = sorted(set(re.findall(r"^function (\w+)\(", code, re.M)))
    code += "\n\nexport { " + ", ".join(names) + " };\n"

    out = Path(__file__).parent / "fixtures" / "swe2d.generated.js"
    out.parent.mkdir(exist_ok=True)
    out.write_text(code)
    print(f"wrote {out}  ({len(code)} bytes, exports: {', '.join(names)})")


if __name__ == "__main__":
    main()
