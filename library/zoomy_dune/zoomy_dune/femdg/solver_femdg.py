"""Explicit DG solver on dune-fem-dg's femDGOperator.

The same model and the same Riemann solver as ``solver_dune.HyperbolicSolver``,
assembled the other way round: the volume terms go in as UFL and are
code-generated by dune, while the face terms are the C++ that zoomy_core
already prints, bound through ``zoomy_flux.hh``.

    solver = FemDGSolver(settings=settings, time_end=10.0)
    solver.setup_simulation(mesh_path, model, initial_condition)
    solver.run_simulation()
"""
import os
import shutil

import param
import ufl
from ufl import as_matrix, as_vector, conditional, dot, grad, sqrt

from dune.femdg import femDGModels, femDGOperator
from dune.femdg.boundary import BndValue
from dune.femdg.rk import femdgStepper

from zoomy_core.misc.misc import Settings, Zstruct
from zoomy_core.transformation.to_c import CppModel, CppNumerics
from zoomy_dune.fvm.solver_dune import HyperbolicSolver, scalar, vec


class FemDGSolver(HyperbolicSolver):
    """femDGOperator march of the same system ``HyperbolicSolver`` integrates.

    Inherits grid, spaces, initial condition, AMR and output: those are
    properties of the backend, not of how the residual is assembled. Only the
    operator and the time step differ.
    """

    limiter = param.Parameter(default="none", doc="femDG limiter; 'none' at DG0")
    rk_order = param.Integer(2, bounds=(1, 4), doc="Explicit Runge-Kutta order")
    c_directory = param.String(".zoomy_c", doc="Where the printed headers land")

    def _lower_model(self, model):
        super()._lower_model(model)
        self._emit_headers()

    def _emit_headers(self):
        """Print Model.H / Numerics.H and park the fixed adapter beside them.

        The parameter values are written as a header rather than passed to the
        flux constructor: dune infers the C++ argument types from the Python
        values, and a list of floats has no unambiguous reading.
        """
        root = os.path.abspath(self.c_directory)
        settings = Settings(name="zoomy_c",
                            output=Zstruct(directory=root, filename="c"))
        CppModel.write_code(self.system_model, settings, filename="Model.H")
        CppNumerics.write_code(self.riemann_solver_cls(self.system_model),
                               settings, filename="Numerics.H")
        self._c_dir = os.path.join(root, ".c_interface")

        values = [float(v) for v in self.parameters]
        with open(os.path.join(self._c_dir, "ZoomyParameters.H"), "w") as out:
            out.write("#pragma once\nstatic constexpr double zoomy_parameters[] = {\n")
            out.write(",\n".join(f"    {v!r}" for v in values))
            out.write("\n};\n")
        shutil.copy(os.path.join(os.path.dirname(os.path.abspath(__file__)),
                                 "zoomy_flux.hh"), self._c_dir)
        self.log(f"printed Model.H, Numerics.H, {len(values)} parameters "
                 f"-> {self._c_dir}")

    def _aux_of(self, u):
        """Aux from the state, not from a stored field: femDGOperator runs its
        own Runge-Kutta stages and offers no hook to refresh one between them.
        Exact while aux is pointwise in Q."""
        zero = as_vector([0.0] * self.n_aux)
        return vec(self.runtime.update_aux_variables(u, zero, self.parameters, 0.0))

    def _model_class(self, initial_condition):
        runtime, numerics, p = self.runtime, self.numerics, self.parameters
        n_var, dim = self.n_var, self.gridView.dimension
        aux_of, row_h = self._aux_of, self._row_h
        u0 = initial_condition(self)

        def as_flux_matrix(expr):
            shape = expr.ufl_shape
            if shape == (n_var, dim):
                return expr
            flat = [expr[i, 0] for i in range(shape[0])] if len(shape) == 2 \
                else [expr[i] for i in range(shape[0])]
            return as_matrix([[flat[i * dim + d] for d in range(dim)]
                              for i in range(n_var)])

        class ZoomyModel:
            dimRange = n_var
            U0 = u0
            userFluxIncludes = [os.path.join(self._c_dir, "zoomy_flux.hh")]
            boundary = {range(1, 1000): BndValue(
                lambda t, x, u, n: vec(runtime.boundary_conditions(
                    0, t, as_vector([x[0], x[1], 0.0]), x[0], u,
                    aux_of(u), p, n)))}

            def F_c(t, x, u):
                return as_flux_matrix(runtime.flux(u, aux_of(u), p))

            def maxWaveSpeed(t, x, u, n):
                return scalar(numerics.local_max_abs_eigenvalue(u, aux_of(u), p, n))

            def velocity(t, x, u):
                return as_vector([u[row_h + 1 + d] / u[row_h] for d in range(dim)])

            def physical(t, x, u):
                return conditional(u[row_h] > 0, 1, 0)

            def jump(t, x, u, w):
                return (u[row_h] - w[row_h]) / (0.5 * (u[row_h] + w[row_h]))

        def source(t, x, u, du):
            return vec(runtime.source(u, aux_of(u), p))

        # Explicit. The model reports implicit_mode == "local_source", but
        # femDGOperator's implicit stage is a global solve, which on Malpasset
        # managed one snapshot in 28 minutes. A cell-local friction update
        # belongs in a split substep, not in S_i.
        ZoomyModel.S_e = source
        return ZoomyModel

    def _set_initial_condition(self, initial_condition):
        super()._set_initial_condition(initial_condition)
        self._initial_condition = initial_condition

    def _build_form(self):
        """femDGOperator in place of the hand-written UFL residual.

        The flux goes in as the userdefined enum rather than as a constructed
        object: zoomy_flux.hh declares that slot over any model, so the
        operator instantiates it with its own wrapper. Handing over an object
        instead would mean naming that wrapper from Python, which is not
        possible before femDGOperator has chosen it.
        """
        models = femDGModels(self._model_class(self._initial_condition), self.V)
        self.operator = femDGOperator(
            models, self.V, limiter=self.limiter,
            advectionFlux="Dune::Fem::AdvectionFlux::Enum::userdefined",
            threading=self.threads > 1, codegen=False)
        # femdgStepper's own `cfl` argument is dead -- the factory ignores it
        # and reads the one passed to the returned callable.
        self.stepper = femdgStepper(order=self.rk_order)(self.operator, self.CFL)
        self._residual = self.Q.copy()
        self._previous = self.Q.copy()

    def step(self, dt=None):
        self.time += self.stepper(self.Q, dt)

    def run_simulation(self):
        interval = self.time_end / self.settings.output.snapshots
        next_output = interval
        self.settle_grid()
        self.write_snapshot()
        n_step = 0
        while self.time < self.time_end:
            if self.adaptive and n_step % self.adapt_interval == 0:
                self.adapt()
            self.step()
            n_step += 1
            if self.time >= next_output:
                self.write_snapshot()
                next_output += interval
                self.log(f"  t = {self.time:8.3f}  dt = {self.stepper.deltaT:.4e}"
                         f"  {self.n_cell} cells")
        self.write_snapshot()
        self.log(f"done, t = {self.time:.3f} -> {self.output_dir}")
        return self.Q, self.Qaux
